defmodule FlowExampleWeb.Examples.Styling.DarkModeLive do
  @moduledoc """
  Dark Mode: switch between dark, light and system mode.

  `"light"` and `"dark"` set the flow `theme` option (rendered as
  `data-lf-theme` on the container). `"system"` leaves it `nil`: a flow
  without a theme follows the site theme (`[data-theme=dark]` on `<html>`).
  Any other theme registered with the `liveflow-theme` Tailwind plugin works
  the same way.
  """
  use FlowExampleWeb, :live_view

  alias FlowExampleWeb.{Examples, FlowEvents}
  alias LiveFlow.{Edge, Handle, Node, State}

  @color_modes [{"Dark", "dark"}, {"Light", "light"}, {"System", "system"}]

  # Themes registered in assets/css/app.css with the liveflow-theme plugin
  @themes ~w(ocean forest sunset synthwave nord dracula cyberpunk coffee)

  @impl true
  def mount(_params, _session, socket) do
    example = Examples.for_module(__MODULE__)

    {:ok,
     socket
     |> assign(example: example, page_title: example.title, themes: @themes)
     |> assign_mode("light")
     |> FlowEvents.assign_flow(build_flow())}
  end

  @impl true
  def render(assigns) do
    ~H"""
    <Layouts.example flash={@flash} example={@example}>
      <.live_component
        module={LiveFlow.Components.Flow}
        id="dark-mode-flow"
        flow={@flow}
        opts={
          %{
            theme: @theme,
            background: :dots,
            controls: true,
            minimap: true,
            fit_view_on_init: true,
            fit_view_options: %{padding: 0.3}
          }
        }
      />

      <%!-- Same place as React Flow's <Panel position="top-right"> --%>
      <div class="absolute top-3 right-3 z-10 w-44 rounded-xl border border-base-300 bg-base-100/90 p-2 shadow-lg backdrop-blur">
        <.form for={@mode_form} id="color-mode-form" phx-change="set_mode">
          <.input
            field={@mode_form[:mode]}
            type="select"
            label="Color mode"
            class={select_class()}
            options={mode_options()}
          />
        </.form>
      </div>

      <:sidebar>
        <.option_group title="How it works">
          <.hint>
            <b>Light</b>
            and <b>Dark</b>
            set <code>opts.theme</code>, rendered as <code>data-lf-theme</code>
            on the flow container.
          </.hint>
          <.hint>
            <b>System</b> leaves <code>theme: nil</code>: the flow inherits the site theme, so
            it follows the switch below (and your OS when the site is on system).
          </.hint>
          <div
            class="mt-2 rounded-lg bg-base-200 px-2.5 py-1.5 font-mono text-[11px] text-base-content/70"
            phx-no-curly-interpolation
          >
            opts: %{theme: <span id="dark-mode-theme" class="text-primary"><%= inspect(@theme) %></span>}
          </div>
        </.option_group>

        <.option_group title="Site theme">
          <Layouts.theme_toggle />
          <.hint>With <b>System</b> selected the flow changes together with the site.</.hint>
        </.option_group>

        <.option_group title="More flow themes">
          <div class="grid grid-cols-2 gap-2">
            <button
              :for={theme <- @themes}
              type="button"
              id={"theme-#{theme}"}
              phx-click="pick_theme"
              phx-value-theme={theme}
              class={[
                "group rounded-lg border p-1.5 text-left transition-all duration-150 hover:-translate-y-0.5 hover:shadow-md active:scale-95",
                if(@mode == theme,
                  do: "border-primary ring-2 ring-primary/30",
                  else: "border-base-300 hover:border-base-content/25"
                )
              ]}
            >
              <.theme_preview theme={theme} />
              <span class="mt-1 block px-0.5 text-xs font-medium capitalize">{theme}</span>
            </button>
          </div>
          <.hint>
            Each theme is a block of <code>--lf-*</code>
            variables generated by the <code>liveflow-theme</code>
            Tailwind plugin in <code>app.css</code>.
          </.hint>
        </.option_group>

        <.option_group title="Event log">
          <.event_log entries={@event_log} />
        </.option_group>
      </:sidebar>
    </Layouts.example>
    """
  end

  attr :theme, :string, required: true

  # A miniature flow painted with the theme's own variables
  defp theme_preview(assigns) do
    ~H"""
    <span
      class="lf-container relative block overflow-hidden rounded-md"
      data-lf-theme={@theme}
      style="height: 2.75rem; cursor: inherit"
    >
      <span
        class="absolute top-1.5 left-1.5 h-3 w-6 rounded-[3px]"
        style="background: var(--lf-node-bg); border: 1px solid var(--lf-node-border)"
      />
      <span
        class="absolute top-[18px] left-7 h-px w-6 rotate-[24deg]"
        style="background: var(--lf-edge-stroke)"
      />
      <span
        class="absolute right-1.5 bottom-1.5 h-3 w-6 rounded-[3px]"
        style="background: var(--lf-node-bg); border: 1.5px solid var(--lf-node-selected-border)"
      />
    </span>
    """
  end

  @impl true
  def handle_event("set_mode", %{"color" => %{"mode" => mode}}, socket) do
    {:noreply, assign_mode(socket, mode)}
  end

  def handle_event("pick_theme", %{"theme" => theme}, socket) do
    {:noreply, assign_mode(socket, theme)}
  end

  def handle_event("lf:" <> _ = event, params, socket) do
    FlowEvents.handle_event(event, params, socket)
  end

  @impl true
  def handle_info({:lf_node_click, _id}, socket), do: {:noreply, socket}

  defp assign_mode(socket, mode) do
    valid = Enum.map(@color_modes, &elem(&1, 1)) ++ @themes
    mode = if mode in valid, do: mode, else: "system"

    assign(socket,
      mode: mode,
      theme: if(mode == "system", do: nil, else: mode),
      mode_form: to_form(%{"mode" => mode}, as: :color)
    )
  end

  defp mode_options do
    [
      {"Color mode", @color_modes},
      {"Flow themes", Enum.map(@themes, &{String.capitalize(&1), &1})}
    ]
  end

  defp build_flow do
    nodes = [
      Node.new("A", %{x: 0, y: 150}, %{label: "A"}, handles: [Handle.source(:right)]),
      Node.new("B", %{x: 250, y: 0}, %{label: "B"}),
      Node.new("C", %{x: 250, y: 150}, %{label: "C"}),
      Node.new("D", %{x: 250, y: 300}, %{label: "D"})
    ]

    edges = [
      Edge.new("A-B", "A", "B"),
      Edge.new("A-C", "A", "C", animated: true),
      Edge.new("A-D", "A", "D", label: "label")
    ]

    State.new(nodes: nodes, edges: edges)
  end
end
